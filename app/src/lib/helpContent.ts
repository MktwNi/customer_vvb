import type { Tab } from '../state';

/**
 * The help center (คู่มือการใช้งาน): what the site can do and how, as data. One list of topics in eight
 * groups, three quick starts and the FAQ. The page (components/Help.tsx) renders it in the app and, before
 * signing in, over the sign-in screen. Copy is plain Thai for sales staff and executives: UI labels in
 * “ ” exactly as on screen, no arrows or symbols (say "แล้วเลือก", "ปุ่มสามจุด").
 */

export interface HelpGroup { id: string; name: string; desc: string }
export interface HelpTopic {
  id: string;
  group: string;
  title: string;
  summary: string;
  steps: string[];
  tips: string[];
  /** Shown as "ใครทำได้: …". */
  roles: string;
  /** The page the topic is about: "ไปที่หน้านี้" switches to it (inside the app only). */
  tab?: Tab;
  keywords: string[];
}
export interface HelpFaq { id: string; q: string; a: string }
export interface QuickStep { text: string; topic: string }
export interface QuickStart {
  id: string;
  title: string;
  who: string;
  steps: QuickStep[];
  /** The one-time team setup: shown before signing in and to whoever can manage the team, with a link
   *  to the developer setup guide (team-sync/README.md). */
  setup?: boolean;
}

