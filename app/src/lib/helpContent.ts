/** For matching: lower case, NFC, "ำ" typed as two characters (nikhahit and sara aa, common in text
 *  pasted from PDFs, Word or LINE) as one, without spaces (Thai is written without them, so "แผน ชำระ"
 *  finds "แผนชำระ") and without quote marks (a label in “ ” is found without them). */
export const normHelp = (s: string) =>
  s
    .normalize('NFC')
    .replace(/\u0E4D([\u0E48-\u0E4B]?)\u0E32/g, '$1\u0E33')
    .toLowerCase()
    .replace(/[\s​-‍⁠﻿“”"'‘’]+/g, '');

/** Words that hold a shorter word they don't mean ("ไลน์" in "ออฟไลน์", "line" in "offline"): a search
 *  for the shorter word doesn't count what is inside them. */
const HIDES = ['ออฟไลน์', 'ออนไลน์', 'offline', 'online'];
/** Normalized `text` holds the normalized query, not only inside one of HIDES. */
function has(text: string, nq: string) {
  for (const w of HIDES) if (w.includes(nq) && !w.startsWith(nq)) text = text.split(w).join('\u0000');
  return text.includes(nq);
}

/** How well a topic matches a normalized query (0 = not at all): its title counts most, then a keyword
 *  that is the query itself or starts with it, its summary, and last its steps and tips. */
export function topicScore(t: HelpTopic, nq: string): number {
  if (!nq) return 0;
  const kw = t.keywords.map(normHelp);
  return (
    (has(normHelp(t.title), nq) ? 4 : 0) +
    (kw.includes(nq) ? 2 : kw.some((k) => k.startsWith(nq)) ? 1 : 0) +
    (has(normHelp(t.summary), nq) ? 1 : 0) +
    // (each line apart, so a match doesn't run from one line into the next)
    (has(normHelp([...t.steps, ...t.tips].join('\u0000')), nq) ? 0.5 : 0)
  );
}

/** The topics (title, keywords, summary, steps and tips) and FAQ (question, answer) matching a query,
 *  best first and in page order within a score; an empty query gives everything in page order. */
export function searchHelp(q: string, topics: HelpTopic[] = HELP_TOPICS, faq: HelpFaq[] = HELP_FAQ): { topics: HelpTopic[]; faq: HelpFaq[] } {
  const nq = normHelp(q);
  if (!nq) return { topics, faq };
  const best = <T>(list: T[], score: (x: T) => number) =>
    list
      .map((x, i) => ({ x, i, s: score(x) }))
      .filter((r) => r.s > 0)
      .sort((a, b) => b.s - a.s || a.i - b.i)
      .map((r) => r.x);
  return {
    topics: best(topics, (t) => topicScore(t, nq)),
    faq: best(faq, (f) => (has(normHelp(f.q), nq) ? 2 : 0) + (has(normHelp(f.a), nq) ? 1 : 0)),
  };
}
